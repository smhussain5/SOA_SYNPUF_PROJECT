/*

GOAL: CHECK THE 2008 BENEFICIARY FILE

DETERMINE IF ROW COUNTS AND UNIQUE MEMBER COUNTS MATCH
DETERMINE HOW MANY MEMBERS HAVE DIFFERING LENGTHS OF PART A AND PART B
DETERMINE HOW MANY MEMBERS DO NOT HAVE PART A
DETERMINE HOW MANY MEMBERS HAVE NON-ZERO HMO MONTHS
DETERMINE HOW MANY MEMBERS HAVE NEGATIVE REIMBURSMENT AMOUNTS

*/

SELECT
	COUNT(*) as row_count,
	COUNT(DISTINCT b8.DESYNPUF_ID) as unique_member_count,
	SUM(CASE WHEN b8.BENE_HI_CVRAGE_TOT_MONS <> b8.BENE_SMI_CVRAGE_TOT_MONS THEN 1 ELSE 0 END) AS diff_bw_parta_partb,
	SUM(CASE WHEN b8.BENE_HI_CVRAGE_TOT_MONS = 0 THEN 1 ELSE 0 END) AS without_parta,
	SUM(CASE WHEN b8.BENE_HMO_CVRAGE_TOT_MONS > 0 THEN 1 ELSE 0 END) AS with_hmo_months,
	SUM(CASE WHEN b8.MEDREIMB_IP < 0 OR b8.MEDREIMB_CAR < 0 OR b8.MEDREIMB_CAR < 0 THEN 1 ELSE 0 END) AS neg_reimbursement_amount
FROM
	bene2008 b8;

